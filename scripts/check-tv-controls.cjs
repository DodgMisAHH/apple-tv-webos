const fs=require('fs'),vm=require('vm'),assert=require('assert');
let calls=[];const context={window:{LauncherControls:{luna:(uri,p,cb)=>{calls.push([uri,p]);cb({stdoutString:JSON.stringify({returnValue:true})});}}},PalmServiceBridge:function(){},setTimeout,clearTimeout};
vm.runInNewContext(fs.readFileSync('app/tv-controls.js','utf8'),context);
const api=context.window.TVControls;
assert.throws(()=>api.request('setTimer','15'));
assert.throws(()=>api.request('output',"tv_speaker'; reboot #"));
assert.throws(()=>api.request('mute','false'));
assert.throws(()=>api.request('arbitrary'));
assert.equal(api.request('powerOff')[1].reason,'remoteKey');
assert.equal(api.request('audio')[0],'luna://com.webos.service.audio/master/getVolume');
assert.equal(api.request('setTimer','120')[1].settings.sleepTimer,'120');
api.call('setTimer','30',r=>assert(r.returnValue));
assert(calls[0][1].command.includes('"sleepTimer":"30"'));
context.window.LauncherControls.luna=(uri,p,cb)=>cb({stdoutString:JSON.stringify({returnValue:false,state:'Active',errorCode:-102,errorText:"The current state must be 'Screen Off'."})});
api.call('screenOn',null,r=>{assert.equal(r.returnValue,false);assert.equal(r.state,'Active');assert.equal(r.errorCode,-102);assert.equal(r.errorText,"The current state must be 'Screen Off'.");});
assert(!api.pending('screenOn'),'Rejected wake releases the power write group');
let before=calls.length;delete context.PalmServiceBridge;
api.call('powerOff',null,r=>assert(r.preview));assert.equal(calls.length,before);
console.log('Allowed settings, injection rejection, master volume routing, service error details and preview isolation passed.');
