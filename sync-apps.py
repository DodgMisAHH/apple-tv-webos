#!/usr/bin/env python3
"""Fetch the TV's apps, icons and HDMI inputs into app/apps.js and app/icons/.

webOS does not let a third-party app list installed apps, so the launcher reads them from here.

    python3 sync-apps.py 192.168.1.50          # sync
    python3 sync-apps.py 192.168.1.50 --list   # just print app ids and titles

Needs: pip install websockets
"""
import asyncio
import hashlib
import json
import os
import stat
import sys
import tempfile
import urllib.request

import lgtv

APP_DIR = os.path.join(lgtv.HERE, "app")
ICON_CACHE = os.path.join(lgtv.HERE, ".sync-apps-icons.json")


def atomic_write(file, data):
    """Publish complete bytes, keeping the previous file on failure."""
    name = None
    try:
        with tempfile.NamedTemporaryFile(dir=os.path.dirname(file), delete=False) as f:
            name = f.name
            f.write(data)
        try:
            mode = stat.S_IMODE(os.stat(file).st_mode)
        except FileNotFoundError:
            mode = 0o644
        os.chmod(name, mode)
        os.replace(name, file)
    finally:
        if name and os.path.exists(name):
            os.unlink(name)


def digest(file):
    try:
        with open(file, "rb") as f:
            return hashlib.sha256(f.read()).hexdigest()
    except OSError:
        return None


def response_list(response, field, require_apps=False):
    values = response.get(field) if isinstance(response, dict) else None
    if (not isinstance(values, list) or response.get("returnValue") is False or
            any(not isinstance(value, dict) for value in values) or (require_apps and not values)):
        raise lgtv.TVError(f"TV did not return a valid {field}; existing app list was retained")
    if require_apps and any(not isinstance(value.get("id"), str) or not value["id"] for value in values):
        raise lgtv.TVError("TV returned an invalid app ID; existing app list was retained")
    return values


def text_or(value, fallback=""):
    return value if isinstance(value, str) and value else fallback


async def main(host, list_only):
    ws = await lgtv.session(host)
    try:
        points = response_list(await lgtv.call(ws, "ssap://com.webos.applicationManager/listLaunchPoints"),
                               "launchPoints", require_apps=True)
        inputs = response_list(await lgtv.call(ws, "ssap://tv/getExternalInputList"), "devices")
    finally:
        await ws.close()

    if list_only:
        for p in points:
            print(f'{p["id"]:45} {text_or(p.get("title"), p["id"])}')
        return

    icon_dir = os.path.join(APP_DIR, "icons")
    os.makedirs(icon_dir, exist_ok=True)
    try:
        with open(ICON_CACHE) as f:
            old_icons = json.load(f)
        if not isinstance(old_icons, dict):
            old_icons = {}
    except (OSError, ValueError):
        old_icons = {}
    next_icons = {}
    ctx = lgtv.insecure_ctx()
    apps = []
    for p in points:
        if p.get("hidden"):
            continue
        name = "".join(ch if ch.isalnum() or ch in "._-" else "_" for ch in p["id"]) + ".png"
        destination = os.path.join(icon_dir, name)
        downloaded = False
        urls = dict.fromkeys(url for url in [p.get("largeIcon"), p.get("icon")]
                             if isinstance(url, str))
        for url in urls:
            if not url.startswith(("http://", "https://")):
                continue
            try:
                with urllib.request.urlopen(url, context=ctx, timeout=10) as response:
                    data = response.read(10 * 1024 * 1024 + 1)
                if not data or len(data) > 10 * 1024 * 1024:
                    raise ValueError("empty or oversized icon")
                atomic_write(destination, data)
                downloaded = True
                break
            except (OSError, ValueError) as error:
                print(f"  no icon for {p['id']}: {error}")
        version = digest(destination)
        if version and (downloaded or old_icons.get(name) == version):
            next_icons[name] = version
        apps.append({
            "id": p["id"],
            "title": text_or(p.get("title"), p["id"]),
            "icon": "icons/" + name + "?v=" + version[:16] if version else "",
            "iconColor": text_or(p.get("iconColor"), text_or(p.get("bgColor"))),
        })
    out = {
        "apps": apps,
        "inputs": [{"appId": d["appId"], "label": text_or(d.get("label"), text_or(d.get("id"), d["appId"]))}
                   for d in inputs if isinstance(d.get("appId"), str) and d["appId"]],
    }
    contents = "// Generated by sync-apps.py: the TV's apps and inputs.\n"
    contents += "window.TV_APPS = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n"
    atomic_write(os.path.join(APP_DIR, "apps.js"), contents.encode("utf-8"))
    # Only remove our old copies, and retain a file replaced by another tool/user.
    for name, previous_digest in old_icons.items():
        if name in next_icons or name != os.path.basename(name) or not name.endswith(".png"):
            continue
        file = os.path.join(icon_dir, name)
        if digest(file) == previous_digest:
            try:
                os.unlink(file)
            except OSError:
                pass
    atomic_write(ICON_CACHE, json.dumps(next_icons, sort_keys=True).encode("utf-8"))
    print(f"Synced {len(apps)} apps and {len(out['inputs'])} inputs.")


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    host = args[0] if args else os.environ.get("TV_HOST")
    if not host:
        sys.exit("usage: sync-apps.py <TV IP> [--list]")
    try:
        asyncio.run(main(host, "--list" in sys.argv))
    except (lgtv.TVError, OSError, asyncio.TimeoutError) as error:
        sys.exit(str(error))
